'use strict';
// Keep the deployment server self-contained: uploading server2.js must not need
// extra analytics sidecars. This generator embeds ordinary, scoped JS functions.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const BEGIN = '// <LITVM_IMPACT_BUNDLE>';
const END = '// </LITVM_IMPACT_BUNDLE>';
const root = path.resolve(__dirname, '..');

function renderBundle(directory = path.join(root, 'backend-impact')) {
  const modules = [
    ['cargarLitvmChainAuditIntegrado', 'litvm-chain-audit.cjs'],
    ['cargarLitvmImpactAnalyticsIntegrado', 'litvm-impact-analytics.cjs']
  ];
  const functions = modules.map(([factory, name]) => {
    const source = fs.readFileSync(path.join(directory, name), 'utf8').replace(/\r\n/g, '\n').trimEnd();
    // The two modules use built-in Node modules only. Never silently embed a
    // new relative/npm dependency that would recreate the deployment failure.
    for (const match of source.matchAll(/require\(['"]([^'"]+)['"]\)/g)) {
      if (!match[1].startsWith('node:')) throw new Error('Non-built-in analytics dependency: ' + match[1]);
    }
    const checksum = crypto.createHash('sha256').update(source).digest('hex');
    return '// Source: ' + name + ' | SHA-256: ' + checksum + '\n' +
      'function ' + factory + '() {\n' +
      "  'use strict';\n  const module = { exports: {} };\n" + source + '\n' +
      '  return module.exports;\n}\n';
  });
  return BEGIN + '\n// Generated by tools/build-impact-backend.cjs; keep source modules in backend-impact/.\n' +
    functions.join('\n') + END;
}

function integrate(source, bundle) {
  const crlf = source.includes('\r\n');
  let result = source.replace(/\r\n/g, '\n')
    .replace("const { createChainAudit } = require('./litvm-chain-audit.cjs');", 'const { createChainAudit } = cargarLitvmChainAuditIntegrado();')
    .replace("const { mountImpactAnalytics } = require('./litvm-impact-analytics.cjs');", 'const { mountImpactAnalytics } = cargarLitvmImpactAnalyticsIntegrado();');
  const start = result.indexOf(BEGIN), end = result.indexOf(END);
  if ((start < 0) !== (end < 0) || (start >= 0 && end < start)) throw new Error('Broken analytics bundle markers');
  if (start >= 0) result = result.slice(0, start) + bundle + result.slice(end + END.length);
  else {
    const anchor = '// Express 4 no propaga rechazos de handlers async al middleware de errores.';
    const position = result.indexOf(anchor);
    if (position < 0) throw new Error('Backend bundle insertion point not found');
    result = result.slice(0, position) + bundle + '\n\n' + result.slice(position);
  }
  if (/require\(['"]\.\/litvm-(?:chain-audit|impact-analytics)\.cjs['"]\)/.test(result)) throw new Error('External analytics require remains');
  return crlf ? result.replace(/\n/g, '\r\n') : result;
}

if (require.main === module) {
  const backend = path.resolve(process.argv[2] || path.join(require('node:os').homedir(), 'Desktop', 'server2.js'));
  const source = fs.readFileSync(backend, 'utf8');
  const next = integrate(source, renderBundle());
  if (next !== source) fs.writeFileSync(backend, next, 'utf8');
  process.stdout.write('Self-contained analytics verified in ' + backend + '\n');
}
module.exports = { renderBundle, integrate, BEGIN, END };
