'use strict';
// Embed the registry in the user's standalone server. Never overwrite a backup.
const fs=require('node:fs');
const path=require('node:path');
const os=require('node:os');
const crypto=require('node:crypto');
const BEGIN='// <COLLECTIONS_BACKEND_BUNDLE>';
const END='// </COLLECTIONS_BACKEND_BUNDLE>';
const ANCHOR='// --- MANEJO DE ERRORES ---';
function renderBundle(sourcePath=path.resolve(__dirname,'../backend-collections/collections.cjs')){
  const source=fs.readFileSync(sourcePath,'utf8').replace(/\r\n/g,'\n').trimEnd();
  for(const match of source.matchAll(/require\(['"]([^'"]+)['"]\)/g))if(!match[1].startsWith('node:'))throw Error('Registry must use injected dependencies or built-in modules: '+match[1]);
  const digest=crypto.createHash('sha256').update(source).digest('hex');
  return `${BEGIN}
// Generated by tools/build-collections-backend.cjs. SHA-256: ${digest}
function cargarColeccionesIntegrado() {
  const module = { exports: {} };
${source}
  return module.exports;
}
try {
  cargarColeccionesIntegrado().mountCollections({
    app, mongoose, ethers, provider: obtenerProveedorLecturaAdmin(),
    adminAuth, csrfProtection, apiLimiter,
    contractAddress: CONTRACTS.ITEMS_CONTRACT.address,
    chainId: CHAIN_ID,
    explorerUrl: EXPLORER_URL,
    confirmations: process.env.COLLECTIONS_CONFIRMATIONS,
    onError: error => console.error('[Colecciones] Consulta fallida:', String(error && (error.code || error.name) || 'unknown').slice(0, 80))
  });
  console.log('Colecciones: API administrativa y registro persistente cargados.');
} catch (error) {
  console.error('[Colecciones] No se pudo iniciar el módulo:', String(error && (error.code || error.name) || 'unknown').slice(0, 80));
  app.use('/api/admin/collections', adminAuth, csrfProtection, (req, res) => {
    res.set('Cache-Control', 'no-store');
    res.status(503).json({error:'collections_initialization_failed', message:'El módulo de colecciones no pudo iniciarse. Revisa el arranque del backend.'});
  });
}
${END}`;
}
function integrate(source,bundle=renderBundle()){
  const crlf=source.includes('\r\n');let result=source.replace(/\r\n/g,'\n');
  const first=result.indexOf(BEGIN),last=result.indexOf(END);
  if((first<0)!==(last<0)||first>=0&&last<first)throw Error('Broken collections bundle markers');
  if(first>=0)result=result.slice(0,first)+bundle+result.slice(last+END.length);
  else {const position=result.indexOf(ANCHOR);if(position<0)throw Error('Backend error handler insertion anchor missing');result=result.slice(0,position)+bundle+'\n\n'+result.slice(position);}
  return crlf?result.replace(/\n/g,'\r\n'):result;
}
if(require.main===module){
  const backend=path.resolve(process.argv[2]||path.join(os.homedir(),'Desktop','server2.js'));
  const before=fs.readFileSync(backend,'utf8');const after=integrate(before);
  if(before!==after){
    const backup=backend+'.before-colecciones-'+new Date().toISOString().replace(/[:.]/g,'-')+'.bak';
    fs.copyFileSync(backend,backup,fs.constants.COPYFILE_EXCL);
    const temp=backend+'.collections-'+process.pid+'.tmp';fs.writeFileSync(temp,after,'utf8');fs.renameSync(temp,backend);
    process.stdout.write('Backup: '+backup+'\n');
  }
  process.stdout.write('Collections registry embedded: '+backend+'\n');
}
module.exports={BEGIN,END,renderBundle,integrate};
